"""The reply fields of every tool both servers register, side by side, read off the reference
pages each server generates (`docs/reference/*.md`), so the page of differences is never typed: a
hand-kept table of two servers' fields is the duplication it exists to avoid.

    uv run python -m scry_core.reply_differences [--mame DIR] [--dosbox-x DIR] [--write]

The directories are the servers' clones (`SCRY_MAME_DIR`, `SCRY_DOSBOX_X_DIR`, else under
`~/Code`). `--write` rewrites `docs/reply-differences.md`, else it is compared. Exit codes: 0
the page agrees (or was rewritten); 1 it differs; 3 INVALID, nothing was compared (a server with
no reference page, or whose pages name no tool).
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections.abc import Sequence
from pathlib import Path

SERVER_PAGES = Path("docs/reference")
OUT_PAGE = Path("docs/reply-differences.md")
_BEGIN = re.compile(r"<!-- scry-reference:begin (\w+) -->")
_ROW = re.compile(r"\| `([^`]+)` \|")


class Invalid(Exception):
    """Nothing was compared."""


def reply_fields(page: str) -> dict[str, list[str]]:
    """Each tool's reply field names, from the `reply field` table under its block."""
    tools: dict[str, list[str]] = {}
    tool, reading = "", False
    for line in page.splitlines():
        if m := _BEGIN.match(line):
            tool, reading = m[1], False
            tools[tool] = []
        elif line.startswith("| reply field"):
            reading = True
        elif reading and tool and (row := _ROW.match(line)):
            tools[tool].append(row[1])
        elif reading and not line.startswith("|"):
            reading = False
    return tools


def _cell(names: Sequence[str]) -> str:
    return ", ".join(f"`{n}`" for n in names) or "-"


def render(mame: dict[str, list[str]], dosbox_x: dict[str, list[str]]) -> str:
    """The page: per tool both servers have, the fields they share and the ones only one has."""
    lines = [
        "# The two servers' replies, side by side",
        "",
        "Generated by `python -m scry_core.reply_differences --write` from each server's",
        "`docs/reference/*.md`, never edited by hand: a test compares it with the run.",
        "",
        "| tool | both | only MAME | only DOSBox-X |",
        "|---|---|---|---|",
    ]
    for tool in sorted(mame.keys() & dosbox_x.keys()):
        left, right = set(mame[tool]), set(dosbox_x[tool])
        lines.append(f"| `{tool}` | {_cell(sorted(left & right))} | {_cell(sorted(left - right))} "
                     f"| {_cell(sorted(right - left))} |")
    lines += ["", f"Only MAME has: {_cell(sorted(mame.keys() - dosbox_x.keys()))}.",
              f"Only DOSBox-X has: {_cell(sorted(dosbox_x.keys() - mame.keys()))}.",
              ""]
    return "\n".join(lines)


def _pages_of(directory: Path) -> dict[str, list[str]]:
    pages = sorted((directory / SERVER_PAGES).glob("*.md"))
    if not pages:
        raise Invalid(f"{directory / SERVER_PAGES} holds no reference page to open")
    tools: dict[str, list[str]] = {}
    for page in pages:
        tools.update(reply_fields(page.read_text(encoding="utf-8")))
    if not tools:
        raise Invalid(f"{directory / SERVER_PAGES} names no tool, so there is nothing to compare")
    return tools


def _clone(env: str, name: str) -> Path:
    return Path(os.environ.get(env) or Path.home() / "Code" / name)


def main(argv: Sequence[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m scry_core.reply_differences", allow_abbrev=False,
                                description="Generate or check the page of the two "
                                            "servers' reply differences.",
                                epilog="Exit codes: 0 agree (or rewritten), 1 differs, 2 a usage "
                                       "error, 3 nothing was compared.")
    p.add_argument("--mame", type=Path, default=_clone("SCRY_MAME_DIR", "scry-mame"))
    p.add_argument("--dosbox-x", type=Path, default=_clone("SCRY_DOSBOX_X_DIR", "scry-dosbox-x"))
    p.add_argument("--write", action="store_true", help=f"rewrite {OUT_PAGE}")
    ns = p.parse_args(argv)
    try:
        wanted = render(_pages_of(ns.mame), _pages_of(ns.dosbox_x))
    except Invalid as e:
        print(f"INVALID: {e}", file=sys.stderr)
        return 3
    if ns.write:
        OUT_PAGE.write_text(wanted, encoding="utf-8")
        print(f"written: {OUT_PAGE}")
        return 0
    held = OUT_PAGE.read_text(encoding="utf-8") if OUT_PAGE.is_file() else ""
    if held != wanted:
        print(f"{OUT_PAGE} differs from the servers' pages: rerun with --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover -- a thin entry, `main` is what the tests run
    sys.exit(main())
